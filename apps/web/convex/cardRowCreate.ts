/**
 * NEO-312 — how a NEW `cardChecklist` row is born, in one place.
 *
 * ## Why this exists
 *
 * Until now the only code that minted a marketplace-derived card row was the
 * insert branch of `commitCardChecklistChunk` (`selectorOptions.ts`): merge the
 * leaf's feature snapshot with what the card itself shows, default Signed By,
 * generate the write-once listing title and description, insert, then patch in
 * the SKU. NEO-312's parallel build copies an insert's cards onto each of its
 * parallels, and every one of those copies has to be born the same way — a
 * copy whose title was generated by a second implementation would disagree
 * with `previewListingTitle`'s Regenerate the moment the two drifted.
 *
 * So the branch body moved here verbatim and both callers share it. What the
 * CALLER still decides is everything that differs between them: the commit
 * resolves players and teams from a review, bounds the pending names and
 * applies the leaf's set-level team default; the parallel build copies those
 * from the insert's card. This module only turns a decided card into a row.
 *
 * ## What it never does
 *
 * It writes no `imageUrls` (a scan belongs to the physical card an operator
 * photographed, not to a checklist entry) and queues no enrichment. Its only
 * read is the caller's lazy `sport()` for the NEO-313 player index. `autographType` is folded into
 * `features.autographed` and is not stored (NEO-217).
 */

